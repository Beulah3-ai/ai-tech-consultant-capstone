from datetime import datetime, timezone
from typing import List
from pydantic import BaseModel, Field, field_validator


class HealthResponse(BaseModel):
    """Schema for GET /health endpoint response."""
    status: str = Field(..., description="Service status", examples=["ok"])
    service: str = Field(default="knowledge-brain", description="Service identifier")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Current UTC timestamp"
    )
    provider: str = Field(default="mock", description="Active AI provider mode")


class QueryRequest(BaseModel):
    """Schema for POST /query endpoint request payload."""
    query: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="User question for the Knowledge Brain",
        examples=["What architecture is recommended for the AI tech consultant?"]
    )

    @field_validator("query")
    @classmethod
    def validate_non_empty_whitespace(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Query cannot be empty or contain only whitespace.")
        return stripped


class QueryResponse(BaseModel):
    """Schema for POST /query endpoint response."""
    query: str = Field(..., description="The original query submitted")
    answer: str = Field(..., description="Generated answer from the knowledge brain")
    answered: bool = Field(..., description="Whether the knowledge brain could answer the question")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence score between 0.0 and 1.0")
    provider: str = Field(
        default="mock",
        description="AI/Knowledge provider identifier. Clearly labeled as 'mock' for local offline testing."
    )
    is_mock: bool = Field(
        default=True,
        description="Explicit flag indicating this response was generated by a mock provider, NOT Claude or a live LLM."
    )
    sources: List[str] = Field(
        default_factory=list,
        description="Knowledge sources or references used"
    )
    disclaimer: str = Field(
        default="Mock AI Response: This response was generated locally by the mock provider for testing and vertical slice validation. It is not generated by Claude or any live LLM.",
        description="Mandatory disclaimer ensuring mock responses are transparently identified."
    )
