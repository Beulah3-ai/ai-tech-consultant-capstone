from datetime import datetime, timezone
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field, field_validator


class HealthResponse(BaseModel):
    """Schema for GET /health endpoint response."""
    status: str = Field(..., description="Service status", examples=["ok"])
    service: str = Field(default="knowledge-brain", description="Service identifier")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Current UTC timestamp"
    )
    provider: str = Field(default="mock", description="Active AI provider mode")
    total_articles: int = Field(default=0, description="Total indexed articles in local knowledge store")


class QueryRequest(BaseModel):
    """Schema for POST /query endpoint request payload."""
    query: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="User question for the Knowledge Brain",
        examples=["How do I set up custom domain forwarding in Brilliant Directories?"]
    )
    provider: Optional[str] = Field(
        default=None,
        description="Optional provider override: 'local_retrieval' or 'mock'. Defaults to system AI_PROVIDER."
    )

    @field_validator("query")
    @classmethod
    def validate_non_empty_whitespace(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Query cannot be empty or contain only whitespace.")
        return stripped


class QueryResponse(BaseModel):
    """Schema for POST /query endpoint response."""
    query: str = Field(..., description="The original query submitted")
    answer: str = Field(..., description="Generated or retrieved answer")
    answered: bool = Field(..., description="Whether the knowledge brain could answer the question")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence score between 0.0 and 1.0")
    provider: str = Field(
        ...,
        description="AI/Knowledge provider identifier ('mock' or 'local_retrieval')"
    )
    is_mock: bool = Field(
        ...,
        description="Explicit flag indicating whether this response was generated by a mock provider."
    )
    sources: List[str] = Field(
        default_factory=list,
        description="Knowledge sources or citations (title and canonical URL)"
    )
    disclaimer: str = Field(
        ...,
        description="Provenance notice explaining whether the response is mock or retrieved from local documentation."
    )


class IngestionRunRequest(BaseModel):
    """Schema for POST /ingestion/run request payload."""
    sitemap_url: str = Field(
        default="https://support.brilliantdirectories.com/support/sitemap.xml",
        description="Target sitemap URL to crawl"
    )
    max_pages: int = Field(
        default=10,
        ge=1,
        le=500,
        description="Configurable ceiling on the number of pages to ingest in this run"
    )
    rate_limit_delay_seconds: float = Field(
        default=0.1,
        ge=0.0,
        le=10.0,
        description="Polite delay between consecutive page fetches in seconds"
    )
    force_resync: bool = Field(
        default=False,
        description="If True, re-fetch and re-verify pages even if already marked unchanged"
    )


class IngestionRunResponse(BaseModel):
    """Schema for POST /ingestion/run response."""
    run_id: str = Field(..., description="Unique run identifier")
    status: str = Field(..., description="Run status: 'completed', 'partial', 'failed'")
    pages_discovered: int = Field(..., description="Total URLs discovered in sitemap")
    pages_processed: int = Field(..., description="Number of pages fetched and processed")
    pages_new: int = Field(..., description="Newly added pages")
    pages_changed: int = Field(..., description="Pages with updated content hashes")
    pages_unchanged: int = Field(..., description="Pages with identical content hashes")
    pages_removed: int = Field(..., description="Pages no longer listed in sitemap")
    errors: List[Dict[str, Any]] = Field(default_factory=list, description="List of errors encountered")
    started_at: datetime = Field(..., description="Timestamp when ingestion started")
    completed_at: Optional[datetime] = Field(default=None, description="Timestamp when ingestion completed")


class IngestionStatusResponse(BaseModel):
    """Schema for GET /ingestion/status response."""
    status: str = Field(..., description="Latest status: 'idle', 'running', 'completed', 'failed'")
    last_run_id: Optional[str] = Field(default=None, description="Identifier of the latest ingestion run")
    last_started_at: Optional[datetime] = Field(default=None, description="Start time of latest run")
    last_completed_at: Optional[datetime] = Field(default=None, description="Completion time of latest run")
    total_articles_stored: int = Field(..., description="Total unique active articles currently in knowledge store")
    pages_new: int = Field(default=0, description="New pages added in latest run")
    pages_changed: int = Field(default=0, description="Changed pages in latest run")
    pages_unchanged: int = Field(default=0, description="Unchanged pages in latest run")
    pages_removed: int = Field(default=0, description="Removed pages in latest run")
    errors_count: int = Field(default=0, description="Number of errors in latest run")
    recent_errors: List[Dict[str, Any]] = Field(default_factory=list, description="Recent error log entries")


class EscalationCreateRequest(BaseModel):
    """Schema for POST /escalations request payload."""
    query: str = Field(..., min_length=1, max_length=2000, description="Unanswered question")
    reason: str = Field(..., min_length=1, max_length=1000, description="Reason for escalation")
    context: Optional[str] = Field(default=None, max_length=4000, description="Relevant context or attempted search")

    @field_validator("query", "reason")
    @classmethod
    def validate_non_empty(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Field cannot be empty or contain only whitespace.")
        return stripped


class EscalationResolveRequest(BaseModel):
    """Schema for POST /escalations/{id}/resolve request payload."""
    expert_answer: str = Field(..., min_length=1, max_length=5000, description="Expert verified answer")
    resolved_by: str = Field(..., min_length=1, max_length=200, description="Name or identifier of the expert")

    @field_validator("expert_answer", "resolved_by")
    @classmethod
    def validate_non_empty(cls, v: str) -> str:
        stripped = v.strip()
        if not stripped:
            raise ValueError("Field cannot be empty or contain only whitespace.")
        return stripped


class EscalationResponse(BaseModel):
    """Schema for Escalation entity response."""
    id: str = Field(..., description="Unique escalation ID")
    query: str = Field(..., description="Unanswered user question")
    reason: str = Field(..., description="Reason for escalation")
    context: Optional[str] = Field(default=None, description="Context provided during escalation")
    status: str = Field(..., description="Escalation status: 'pending', 'resolved', 'dismissed'")
    expert_answer: Optional[str] = Field(default=None, description="Answer provided upon resolution")
    resolved_by: Optional[str] = Field(default=None, description="Expert identifier who resolved this")
    created_at: datetime = Field(..., description="Escalation creation timestamp")
    resolved_at: Optional[datetime] = Field(default=None, description="Resolution timestamp")
