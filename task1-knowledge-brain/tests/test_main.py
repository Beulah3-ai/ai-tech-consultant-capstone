import pytest
from fastapi.testclient import TestClient
from app.main import app

client = TestClient(app)


def test_health_check_returns_ok():
    """Verify GET /health returns 200 with status ok and mock provider."""
    response = client.get("/health")
    assert response.status_code == 200
    data = response.json()
    assert data["status"] == "ok"
    assert data["service"] == "knowledge-brain"
    assert "provider" in data
    assert "timestamp" in data


def test_valid_query_returns_mock_response():
    """Verify POST /query with an answerable question returns 200 and clearly labeled mock response."""
    payload = {"query": "What architecture is recommended for the AI tech consultant?"}
    response = client.post("/query", json=payload)
    assert response.status_code == 200
    data = response.json()
    assert data["query"] == payload["query"]
    assert data["answered"] is True
    assert data["confidence"] > 0.0
    assert data["provider"] == "mock"
    assert data["is_mock"] is True
    assert "[MOCK PROVIDER]" in data["answer"]
    assert "Mock AI Response:" in data["disclaimer"]
    assert len(data["sources"]) > 0


def test_query_tech_stack():
    """Verify POST /query returns tech stack information from mock knowledge."""
    payload = {"query": "What is the tech stack?"}
    response = client.post("/query", json=payload)
    assert response.status_code == 200
    data = response.json()
    assert data["answered"] is True
    assert "FastAPI" in data["answer"]
    assert data["is_mock"] is True


def test_invalid_query_empty_string():
    """Verify POST /query with an empty string returns 422 Unprocessable Entity."""
    response = client.post("/query", json={"query": ""})
    assert response.status_code == 422


def test_invalid_query_whitespace_only():
    """Verify POST /query with only whitespace returns 422 Unprocessable Entity."""
    response = client.post("/query", json={"query": "     "})
    assert response.status_code == 422


def test_invalid_query_missing_payload():
    """Verify POST /query with missing body or missing query field returns 422."""
    response = client.post("/query", json={})
    assert response.status_code == 422

    response = client.post("/query", json={"wrong_key": "some value"})
    assert response.status_code == 422


def test_unanswerable_query_returns_graceful_fallback():
    """Verify POST /query with a question the knowledge base cannot answer returns answered=False with fallback."""
    payload = {"query": "How do I make sourdough bread with walnuts and raisins?"}
    response = client.post("/query", json=payload)
    assert response.status_code == 200
    data = response.json()
    assert data["query"] == payload["query"]
    assert data["answered"] is False
    assert data["confidence"] == 0.0
    assert data["provider"] == "mock"
    assert data["is_mock"] is True
    assert "cannot answer this question" in data["answer"]
    assert len(data["sources"]) == 0
    assert "Mock AI Response:" in data["disclaimer"]


def test_mock_transparency_never_claims_claude():
    """Verify that mock provider explicitly announces itself as mock and does not claim to be Claude."""
    payload = {"query": "Who are you and what AI model is running?"}
    response = client.post("/query", json=payload)
    assert response.status_code == 200
    data = response.json()
    assert data["is_mock"] is True
    assert data["provider"] == "mock"
    assert "not generated by Claude" in data["disclaimer"]
