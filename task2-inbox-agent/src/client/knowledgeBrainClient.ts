import { KnowledgeBrainQueryResponse } from "../types.js";

export interface KnowledgeBrainClientConfig {
  baseUrl?: string;
  timeoutMs?: number;
  useMockFallback?: boolean;
}

export interface KnowledgeBrainResult {
  success: boolean;
  data?: KnowledgeBrainQueryResponse;
  error?: string;
  isMockFallback?: boolean;
}

export class KnowledgeBrainClient {
  private baseUrl: string;
  private timeoutMs: number;
  private useMockFallback: boolean;

  constructor(config: KnowledgeBrainClientConfig = {}) {
    this.baseUrl = (config.baseUrl || process.env.KNOWLEDGE_BRAIN_URL || "http://localhost:8000").replace(/\/+$/, "");
    this.timeoutMs = config.timeoutMs ?? parseInt(process.env.KNOWLEDGE_BRAIN_TIMEOUT_MS || "4000", 10);
    this.useMockFallback = config.useMockFallback ?? (process.env.MOCK_KNOWLEDGE_BRAIN === "true");
  }

  async query(question: string, providerOverride?: string): Promise<KnowledgeBrainResult> {
    if (this.useMockFallback) {
      return {
        success: true,
        isMockFallback: true,
        data: this.generateOfflineMockResponse(question),
      };
    }

    const endpoint = `${this.baseUrl}/query`;
    try {
      const response = await fetch(endpoint, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Accept: "application/json",
        },
        body: JSON.stringify({
          query: question,
          provider: providerOverride || process.env.AI_PROVIDER || "local_retrieval",
        }),
        signal: AbortSignal.timeout(this.timeoutMs),
      });

      if (!response.ok) {
        const errText = await response.text().catch(() => "");
        return {
          success: false,
          error: `Knowledge Brain returned HTTP ${response.status}: ${errText.slice(0, 200)}`,
        };
      }

      const json = (await response.json()) as KnowledgeBrainQueryResponse;
      return {
        success: true,
        data: json,
        isMockFallback: false,
      };
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : String(err);
      return {
        success: false,
        error: `Failed to connect to Knowledge Brain at ${this.baseUrl}: ${message}`,
      };
    }
  }

  private generateOfflineMockResponse(question: string): KnowledgeBrainQueryResponse {
    const qLower = question.toLowerCase();

    if (qLower.includes("custom domain") || qLower.includes("a-record") || qLower.includes("dns")) {
      return {
        query: question,
        answer: "[MOCK PROVIDER] To connect your custom domain to Brilliant Directories, point your A-Record to 54.208.12.34 and configure a CNAME for www.",
        answered: true,
        confidence: 0.95,
        provider: "mock",
        is_mock: true,
        sources: ["Connecting Custom Domains (https://support.brilliantdirectories.com/articles/custom-domains)"],
        disclaimer: "Mock AI Response: Generated by offline mock provider for testing.",
      };
    }

    if (qLower.includes("stripe") || qLower.includes("payment gateway") || qLower.includes("checkout")) {
      return {
        query: question,
        answer: "[MOCK PROVIDER] Enter your Stripe Publishable Key and Secret Key in Admin under Finance > Payment Gateways.",
        answered: true,
        confidence: 0.92,
        provider: "mock",
        is_mock: true,
        sources: ["Setting Up Stripe Payment Gateway (https://support.brilliantdirectories.com/articles/stripe-gateway)"],
        disclaimer: "Mock AI Response: Generated by offline mock provider for testing.",
      };
    }

    if (qLower.includes("csv") || qLower.includes("import") || qLower.includes("bulk member")) {
      return {
        query: question,
        answer: "[MOCK PROVIDER] Download the CSV template from Members > Member Import to bulk upload directory members.",
        answered: true,
        confidence: 0.90,
        provider: "mock",
        is_mock: true,
        sources: ["Bulk Member Import Guide (https://support.brilliantdirectories.com/articles/member-import)"],
        disclaimer: "Mock AI Response: Generated by offline mock provider for testing.",
      };
    }

    // Default abstention for out-of-scope or unverified topics
    return {
      query: question,
      answer: "I cannot answer this question based on the currently indexed Brilliant Directories knowledge base. Insufficient evidence was found.",
      answered: false,
      confidence: 0.0,
      provider: "mock",
      is_mock: true,
      sources: [],
      disclaimer: "Mock AI Response: Generated by offline mock provider for testing.",
    };
  }
}
